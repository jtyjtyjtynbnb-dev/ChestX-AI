const zh = Object.fromEntries(Object.keys(en).map((key) => [key, key]));

export const i18n = createI18n({
  legacy: false,
  globalInjection: true,
  locale: (typeof localStorage !== 'undefined' && localStorage.getItem(STORAGE_KEY)) || 'zh',
  fallbackLocale: 'zh',
  messages: { zh, en },
  flatJson: true,
  missingWarn: false,
  fallbackWarn: false,
});

if (typeof document !== 'undefined') {
  document.documentElement.lang = i18n.global.locale.value === 'en' ? 'en' : 'zh-CN';
}

export function getLocale() {
  return i18n.global.locale.value === 'en' ? 'en' : 'zh';
}

export function setLocale(locale) {
  const next = locale === 'en' ? 'en' : 'zh';
  i18n.global.locale.value = next;
  try { localStorage.setItem(STORAGE_KEY, next); } catch { /* storage may be disabled */ }
  document.documentElement.lang = next === 'en' ? 'en' : 'zh-CN';
  window.dispatchEvent(new CustomEvent('dsh-locale-change', { detail: next }));
}

export function toggleLocale() {
  setLocale(getLocale() === 'en' ? 'zh' : 'en');
}
